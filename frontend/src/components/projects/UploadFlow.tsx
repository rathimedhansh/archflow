"use client";

import { useState } from "react";
import AutoResultSummary from "@/components/AutoResultSummary";
import FloorPlanPreview from "@/components/FloorPlanPreview";
import ProcessingSteps from "@/components/ProcessingSteps";
import UploadDropzone from "@/components/UploadDropzone";
import { useAutoInterpret } from "@/hooks/useAutoInterpret";
import { useFloorPlanUpload } from "@/hooks/useFloorPlanUpload";
import { api, ApiError } from "@/lib/api";
import { buildSteps } from "@/lib/interpretation/steps";
import { ErrorNote } from "./ui";

/** A drawing in the supported style, generated by `backend/evaluation/synth.py` (seed 6): free to use. */
const SAMPLE_PLAN = "/samples/sample-apartment.png";

/**
 * The M2/M6 upload experience (upload → live detection steps → result summary), unchanged, with one
 * addition: the uploaded plan is attached to the property project before detection starts.
 */
export default function UploadFlow({ projectId, onAttached }: { projectId: string; onAttached?: () => void }) {
  const { state, upload, reset } = useFloorPlanUpload();
  const auto = useAutoInterpret();
  const [autoEnabled, setAutoEnabled] = useState(true);
  // Whether the step list includes the detection stages (fixed once an upload starts).
  const [withAuto, setWithAuto] = useState(true);
  const [attachError, setAttachError] = useState<string | null>(null);

  const onFile = async (file: File) => {
    auto.reset();
    setAttachError(null);
    setWithAuto(autoEnabled);
    const record = await upload(file);
    if (!record) return;
    try {
      await api.attachFloorPlan(projectId, record.id);
      onAttached?.();
    } catch (err) {
      reset();
      return setAttachError(err instanceof ApiError ? err.message : "The plan was uploaded but could not be added to this property.");
    }
    if (autoEnabled) void auto.run(record.id);
  };
  const startOver = () => {
    auto.reset();
    reset();
  };

  const uploading = state.phase === "uploading" || state.phase === "processing";
  const showSteps = uploading || auto.state.phase === "running";
  const fileName = state.phase === "uploading" || state.phase === "processing" ? state.fileName : state.phase === "ready" ? state.plan.original_filename : null;

  if (state.phase === "ready" && auto.state.phase === "done") {
    return <AutoResultSummary image={state.plan} interpretation={auto.state.interpretation} onReset={startOver} />;
  }
  if (state.phase === "ready" && !showSteps) {
    return (
      <div className="space-y-5">
        {auto.state.phase === "error" && <ErrorNote>{auto.state.message} You can retry, or trace the plan by hand.</ErrorNote>}
        <FloorPlanPreview plan={state.plan} onReset={startOver} onAutoGenerate={() => {
          setWithAuto(true);
          void auto.run(state.plan.id);
        }} />
      </div>
    );
  }
  return (
    <div className="mx-auto max-w-2xl space-y-5">
      {showSteps ? (
        <ProcessingSteps steps={buildSteps(state.phase, withAuto ? auto.state : null)} fileName={fileName}
          progress={state.phase === "uploading" ? state.progress : null} />
      ) : (
        <>
          <UploadDropzone onFile={(f) => void onFile(f)} />
          <label className="flex cursor-pointer items-start gap-3 rounded-lg border border-border bg-surface px-4 py-3.5 text-sm transition-colors hover:border-border-strong">
            <input type="checkbox" className="mt-0.5 h-4 w-4 shrink-0 accent-[var(--accent)]" checked={autoEnabled} onChange={(e) => setAutoEnabled(e.target.checked)} data-testid="auto-toggle" />
            <span>
              <span className="font-medium">Detect the walls and rooms for me</span>
              <span className="mt-0.5 block leading-relaxed text-muted">
                ARCHFLOW finds walls, rooms, doors and windows automatically; you review and correct them in the editor.
                Works best on clean black-and-white plans with solid, thick walls.
              </span>
            </span>
          </label>
          <p className="text-center text-sm text-muted">
            No plan at hand?{" "}
            <button type="button" className="font-medium text-accent underline decoration-accent/30 underline-offset-[3px] hover:decoration-accent" onClick={async () => {
              setAttachError(null);
              try {
                const res = await fetch(SAMPLE_PLAN);
                if (!res.ok) throw new Error();
                void onFile(new File([await res.blob()], "sample-apartment.png", { type: "image/png" }));
              } catch {
                setAttachError("The sample plan could not be loaded.");
              }
            }}>
              Use the sample apartment
            </button>{" "}
            (a 7-room plan with an 11.75 m dimension to calibrate from).
          </p>
        </>
      )}
      {state.phase === "error" && <ErrorNote>{state.message}</ErrorNote>}
      {attachError && <ErrorNote>{attachError}</ErrorNote>}
    </div>
  );
}
