"""Measure the automatic interpreter: `python -m evaluation.run [--out ../docs/CV_EVALUATION.md]`.

Every image goes through the same path as a real upload (PNG encode -> upload normalisation
-> pipeline), and every number in the report is computed here, from these runs.
"""

import argparse
import json
import statistics
import time
from pathlib import Path

import cv2
import numpy as np

from app.interpretation.opencv import PIPELINE_VERSION, interpret_image
from app.processing.image_intake import normalize_upload
from evaluation.cases import Case, build_cases
from evaluation.metrics import PR, PlanScores, score

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SAMPLE = ROOT / "docs" / "samples" / "m2-sample-plan.png"
GROUPS = (
    ("supported", "Supported style (synthetic)"),
    ("real", "Real-world images (hand-traced ground truth)"),
    ("hand-drawn", "Hand-authored ground truth"),
    ("out-of-scope", "Out-of-scope drawings (synthetic, expected failures)"),
)


def run_case(case: Case) -> dict:
    ok, png = cv2.imencode(".png", case.image)
    assert ok
    normalized = normalize_upload(png.tobytes())
    image = cv2.imdecode(np.frombuffer(normalized.png_bytes, np.uint8), cv2.IMREAD_GRAYSCALE)
    t0 = time.perf_counter()
    result = interpret_image(image, floorplan_id="eval", width_px=normalized.width, height_px=normalized.height)
    ms = (time.perf_counter() - t0) * 1000
    s = score(case.truth, result.plan)
    if not case.scale_known:
        s.scale_rel_error = None
    return {
        "name": case.name, "group": case.group, "description": case.description, "notes": case.notes,
        "supported": result.report.supported, "reason": result.report.reason,
        "overall_confidence": result.report.overall_confidence, "scale_source": result.report.scale.source if result.report.scale else None,
        "warnings": result.report.warnings, "ms": round(ms, 1), "scores": s.as_dict(), "_scores": s,
    }


def _sum(prs: list[PR]) -> PR:
    correct = None if all(p.correct is None for p in prs) else sum(p.matched if p.correct is None else p.correct for p in prs)
    return PR(sum(p.truth for p in prs), sum(p.detected for p in prs), sum(p.matched for p in prs), correct)


def _pct(v: float | None) -> str:
    return "n/a" if v is None else f"{v * 100:.1f}%"


def aggregate(rows: list[dict]) -> dict:
    scores: list[PlanScores] = [r["_scores"] for r in rows]
    t_len = [(s.wall_length_recall, s.wall_length_precision) for s in scores]
    scale_errs = [s.scale_rel_error for s in scores if s.scale_rel_error is not None]
    ious = [s.room_mean_iou for s in scores if s.room_mean_iou is not None]
    recalls = [v[0] for v in t_len if v[0] is not None]
    precisions = [v[1] for v in t_len if v[1] is not None]
    agg = {
        "plans": len(rows),
        "rejected_as_unsupported": sum(1 for r in rows if not r["supported"]),
        "wall_length_recall_mean": statistics.mean(recalls) if recalls else None,
        "wall_length_precision_mean": statistics.mean(precisions) if precisions else None,
        "median_ms": statistics.median(r["ms"] for r in rows),
        "room_mean_iou": statistics.mean(ious) if ious else None,
        "scale_rel_error_median": statistics.median(scale_errs) if scale_errs else None,
        "scale_rel_error_max": max(scale_errs) if scale_errs else None,
        "scale_within_10pct": (sum(1 for e in scale_errs if e <= 0.10) / len(scale_errs)) if scale_errs else None,
    }
    for k in ("walls", "rooms", "doors", "windows"):
        pr = _sum([getattr(s, k) for s in scores])
        agg[k] = {"truth": pr.truth, "detected": pr.detected, "matched": pr.matched, "precision": pr.precision, "recall": pr.recall}
    errs = [s.door_width_error for s in scores if s.door_width_error is not None]
    agg["door_width_error_mean"] = statistics.mean(errs) if errs else None
    errs = [s.window_width_error for s in scores if s.window_width_error is not None]
    agg["window_width_error_mean"] = statistics.mean(errs) if errs else None
    return agg


def _cell(e: dict) -> str:
    # Extra = detections that match nothing. For walls one detection may cover two collinear truth walls.
    good = e["matched"] if e.get("correct") is None else e["correct"]
    return f"{e['matched']}/{e['truth']} (+{e['detected'] - good})"


def markdown(rows: list[dict]) -> str:
    out = [
        "# CV evaluation results",
        "",
        f"Generated by `python -m evaluation.run` (pipeline `{PIPELINE_VERSION}`). Every number below was measured by running the",
        "pipeline on the listed images; see `backend/evaluation/metrics.py` for the exact definitions.",
        "",
        "**Read these numbers with their limits:** the *supported* set is synthetic (generated plans with exact ground truth, drawn",
        "in the supported style with random variation in scale, wall thickness, symbols, clutter, noise, blur and JPEG) and was",
        "written by the same team as the detector. It shows that the pipeline does what it is designed to do on that style. It does",
        "**not** measure accuracy on arbitrary real-world floor plans, which vary far more. The *real-world* set is tiny (one real",
        "plan and one image that is not a plan), so its numbers are anecdotes, not statistics. The real plan was also looked at",
        "while fixing door detection next to wall junctions, so it is not a held-out test. Failure analysis: ARCHFLOW_PLAN.md (M6).",
        "The supported input style is defined in `docs/SUPPORTED_FLOOR_PLANS.md`.",
        "",
    ]
    for group, title in GROUPS:
        rs = [r for r in rows if r["group"] == group]
        if not rs:
            continue
        a = aggregate(rs)
        out += [f"## {title} ({a['plans']} image{'s' if a['plans'] != 1 else ''})", ""]
        if group != "out-of-scope":
            out += [
                "| Element | Truth | Detected | Matched | Precision | Recall |",
                "|---|---:|---:|---:|---:|---:|",
            ]
            for k in ("walls", "rooms", "doors", "windows"):
                e = a[k]
                out.append(f"| {k.capitalize()} | {e['truth']} | {e['detected']} | {e['matched']} | {_pct(e['precision'])} | {_pct(e['recall'])} |")
            out += [
                "",
                f"* Wall length found (recall): {_pct(a['wall_length_recall_mean'])} · detected wall length on a real wall (precision): {_pct(a['wall_length_precision_mean'])}",
                f"* Mean room IoU of matched rooms: {_pct(a['room_mean_iou'])}",
                f"* Mean width error of matched doors: {_pct(a['door_width_error_mean'])} · windows: {_pct(a['window_width_error_mean'])}",
                f"* Scale (metres per pixel) relative error: median {_pct(a['scale_rel_error_median'])}, worst {_pct(a['scale_rel_error_max'])}, within 10%: {_pct(a['scale_within_10pct'])}",
                f"* Rejected as unsupported: {a['rejected_as_unsupported']} · median pipeline time: {a['median_ms']:.0f} ms",
                "",
            ]
        out += [
            "| Plan | Description | Result | Walls | Wall length R / P | Rooms | Doors | Windows | Scale err (source) |",
            "|---|---|---|---|---|---|---|---|---:|",
        ]
        for r in rs:
            s = r["scores"]
            res = "rejected: " + (r["reason"] or "") if not r["supported"] else f"ok ({r['overall_confidence']:.2f})"
            wl = f"{_pct(s['wall_length_recall'])} / {_pct(s['wall_length_precision'])}"
            scale = _pct(s["scale_rel_error"]) + (f" ({r['scale_source']})" if r["scale_source"] and s["scale_rel_error"] is not None else "")
            out.append(
                f"| {r['name']} | {r['description']} | {res} | {_cell(s['walls'])} | {wl} | {_cell(s['rooms'])} | "
                f"{_cell(s['doors'])} | {_cell(s['windows'])} | {scale} |"
            )
        out += ["", "Cells read `matched/truth (+detections that match nothing)`.", ""]
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=30)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "CV_EVALUATION.md")
    ap.add_argument("--json", type=Path, default=Path(__file__).parent / "results.json")
    ap.add_argument("--sample", type=Path, default=DEFAULT_SAMPLE)
    args = ap.parse_args()
    rows = [run_case(c) for c in build_cases(args.n, str(args.sample) if args.sample.is_file() else None)]
    args.out.write_text(markdown(rows), encoding="utf-8")
    serial = [{k: v for k, v in r.items() if k != "_scores"} for r in rows]
    summary = {g: aggregate([r for r in rows if r["group"] == g]) for g, _ in GROUPS if any(r["group"] == g for r in rows)}
    args.json.write_text(json.dumps({"pipeline": PIPELINE_VERSION, "summary": summary, "cases": serial}, indent=1, default=str), encoding="utf-8")
    for g, a in summary.items():
        print(g, json.dumps({k: (round(v, 4) if isinstance(v, float) else v) for k, v in a.items()}))
    for r in rows:
        s = r["scores"]
        flag = "" if all((s[k]["recall"] in (None, 1.0)) and (s[k]["precision"] in (None, 1.0)) for k in ("walls", "rooms", "doors", "windows")) else "  <-- imperfect"
        print(f"{r['name']:22s} sup={r['supported']!s:5} walls {_cell(s['walls'])} rooms {_cell(s['rooms'])} "
              f"doors {_cell(s['doors'])} win {_cell(s['windows'])} scale {_pct(s['scale_rel_error'])}{flag}"
              + (f"  [{r['reason']}]" if r["reason"] else ""))


if __name__ == "__main__":
    main()
